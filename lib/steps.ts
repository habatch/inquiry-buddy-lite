/**
 * 探究ワークブックの全ステップ定義 (AI なし版)
 *
 * AI 版の system prompt にあった「答えを教えず、問いで引き出す」方針を、
 * 固定の問いカード + 考える角度 (ヒント) + 自己チェックリストに置き換えている。
 * ヒントは「答えの雛形」ではなく「考える方向」だけを示す。
 */

export interface Field {
  id: string;
  label: string;
  /** 問いの補足 (小さく表示) */
  help?: string;
  placeholder?: string;
  /** 詰まったとき用: 考える角度 (答えそのものは書かない) */
  hints?: string[];
  /** 必須かどうか (既定 true) */
  required?: boolean;
  /** 必須入力として認める最小文字数 (既定 10) */
  minChars?: number;
  rows?: number;
}

export type Widget =
  | "topics" // Step 1: 興味分野ごとの話題カード
  | "search" // Step 4: 論文/記事の検索リンク生成
  | "compose" // Step 8: A〜D を連結して発表文の下書きを作る
  | "rehearsal" // Step 9: 字数・秒数メーター + 1 分タイマー + 想定質問集
  | "outreach"; // Step 10: 学校の外へ届ける 3 つの道

export interface StepDef {
  id: number;
  name: string;
  icon: string;
  goal: string;
  unlockScore?: number;
  /** ステップ冒頭の語りかけ */
  intro: string;
  /** 前のステップの回答を「ここまでの探究」として上に表示する (step.fieldId) */
  recall?: { key: string; label: string }[];
  widget?: Widget;
  fields: Field[];
  /** 全部チェックすると +30 pt、次のステップへ進める */
  checklist: string[];
}

